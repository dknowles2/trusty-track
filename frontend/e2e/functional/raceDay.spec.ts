test('finishing a round built via Add Round, with no championship yet, offers to add one rather than claiming the race is over (#874)', async ({
    page,
}) => {
    // The reported bug: the summary modal said "Race Complete!" — "Every
    // heat has been run. Here's where to go next: See Final Standings" — the
    // moment a race's sole preliminary round finished, when the operator had
    // not yet had a chance to add a championship round from **Add Round**
    // (as opposed to the wizard, which pre-creates one up front, which is
    // why `createSchedule`'s wizard-built races above never tripped this).
    //
    // The tempting fix — only claim completion once a championship round
    // exists — was tried and reverted: a race that really is prelims-only
    // (raced via the wizard with no championship configured, exactly
    // `createSchedule(page, raceId)` with no second argument, as the
    // adjacent #856 test does) produces the identical shape and must still
    // raise the summary. There is no stored fact distinguishing "done" from
    // "not done building the schedule yet," so the fix is honesty rather
    // than suppression: the modal still appears, but says "No More Heats
    // Scheduled" and offers a way to add the round it might be missing,
    // alongside — never instead of — the standings link that always applies.
    //
    // `createRound` here is exactly the shape "Add Round" sends for a plain
    // general round: no `advancementSource`, unlike `createSchedule`'s
    // wizard call which can pre-create a championship round too.
    const { raceId, racers, laneCount } = await seedRace(page, 'Race Day One Round At A Time');

    await gql(
        page,
        `mutation AddGeneralRound($raceId: Int!, $roundData: RoundCreateInput!) {
            createRound(raceId: $raceId, roundData: $roundData) { id }
        }`,
        {
            raceId,
            roundData: { schedulingStrategy: 'PPC', name: 'Round 1', generalType: 'ALL', runsPerLane: 1 },
        },
    );

    await page.goto(`/race/${raceId}/control/race`);
    await expect(page.getByText('Ready to start')).toBeVisible({ timeout: 30000 });

    const heats = await readHeats(page, raceId);
    await recordRound(page, heats, racers);

    // Not "Race Complete!" — this schedule has no round that could only be a
    // genuine ending yet.
    const notDone = page.getByRole('dialog', { name: 'No More Heats Scheduled' });
    await expect(notDone).toBeVisible({ timeout: 30000 });
    await expect(page.getByRole('dialog', { name: 'Race Complete!' })).toHaveCount(0);
    await expect(notDone.getByRole('link', { name: 'Add a Championship Round' })).toHaveAttribute(
        'href',
        `/race/${raceId}/control`,
    );
    // The standings link is still offered — a prelims-only race really is
    // done here, and this modal cannot tell the two apart.
    await expect(notDone.getByRole('link', { name: /Final Standings/i })).toHaveAttribute(
        'href',
        `/race/${raceId}/standings`,
    );
    await notDone.getByRole('button', { name: '×' }).click();
    await expect(notDone).toBeHidden();

    // The operator now adds the championship round the modal offered.
    // Once *that* is fully raced too, the real "Race Complete!" must show.
    const rounds = await readRounds(page, raceId);
    const prelim = rounds.find((r) => r.advancementSource === null)!;
    await gql(
        page,
        `mutation AddFinal($raceId: Int!, $roundData: RoundCreateInput!) {
            createRound(raceId: $raceId, roundData: $roundData) { id }
        }`,
        {
            raceId,
            roundData: {
                schedulingStrategy: 'PPC',
                name: 'Pack Final',
                advancementSource: 'ALL',
                advancementNumRacers: laneCount,
                runsPerLane: 1,
            },
        },
    );

    const final = (await readRounds(page, raceId)).find((r) => r.id !== prelim.id)!;
    const finalHeats = (await readHeats(page, raceId))
        .filter((h) => h.roundId === final.id)
        .sort((a, b) => a.heatNumber - b.heatNumber);

    // All but the last final heat go straight to the backend, the same
    // shape the #856 test above uses. Two reasons, not one:
    //
    // `race_state:{raceId}`'s subscription used to be able to lose a
    // `HEAT_RESULT` event outright under a fast enough burst — its bounded
    // queue's drop-oldest policy assumes every payload is a superseded-by-
    // the-next snapshot, which is false for a delta naming one heat's own
    // result (#896, fixed in `backend/api/pubsub.py` — that channel no
    // longer drops). Reloading before the last heat, and running that one
    // heat live through the fake timer, is a second, independent line of
    // defence that does not depend on that fix staying in place: a reload
    // re-reads the true state fresh over plain HTTP regardless of what the
    // subscription queue did, and `TimerManager`'s own result path
    // publishes with no specific `kind`, which the client always treats as
    // needing a refetch (`raceCompletion.ts`'s docstring covers the same
    // "no event, so recovered by comparing snapshots" territory this event
    // stream sits on top of).
    //
    // It also drives the completion this test is actually about the way an
    // operator would: live, on the Race screen, rather than by writing the
    // race's last own result from outside the browser entirely and hoping
    // the summary catches up (#916 — see `raceCompletion.ts`'s
    // `heatSetKey` and `raceFlow.ts`'s `raceSummaryKey` for the client-side
    // half of that fix, which this test also exercises: the "Round
    // Complete!" summary for the championship field filling in fires
    // first, and "Race Complete!" has to override it rather than being
    // masked by it).
    await recordRound(page, finalHeats.slice(0, -1), racers);
    await page.reload();
    await expect(page.getByText('Ready to start')).toBeVisible({ timeout: 30000 });
    await page.getByRole('button', { name: 'Start Timer' }).click();
    await page.getByRole('button', { name: 'Finish Heat' }).click();

    const summary = page.getByRole('dialog', { name: 'Race Complete!' });
    await expect(summary).toBeVisible({ timeout: 30000 });
    await expect(summary.getByRole('link', { name: 'Add a Championship Round' })).toHaveCount(0);
});

test('a round summary can be raised again once its round is decided a second time (#856)', async ({
    page,
}) => {
    // `RaceControl`'s `roundSummary` sticky state used to clear only at its
    // own two explicit call sites — re-running the *active* heat (which
    // clears the result through `handleRunHeat`), and dismissing the summary
    // (which clears it through `handleNextHeat`). Dismissing the summary by
    // its own "×" goes through neither: it calls `flow.dismissSummary`
    // directly, hiding the modal without touching `roundSummary` at all.
    //
    // Correcting a result through Edit/Override (`handleUpdateResult`) is a
    // third path, and it never clears `roundSummary` either. That would be
    // invisible on its own — the modal is already hidden — except that
    // `raceFlow.ts`'s own "already summarised this round" guard
    // (`haveSummarised`/`summarisedRoundId`) only resets when `roundSummary`
    // itself genuinely becomes falsy. If it never does, a round that
    // un-decides and is later decided again is never re-announced: the
    // stale `roundSummary` keeps naming the same round id, so the guard
    // reads the second decision as one it has already shown.
    //
    // All but the last prelim heat are written straight to the backend —
    // fast, and it does not matter how the client learns about them, because
    // `updateHeatResult`'s own publish carries only the one heat it touched
    // (#12's cache-merge optimization) and never forces a refetch. Only the
    // *last* heat is run on screen, through the fake timer, because the
    // timer's own result path publishes with no specific `kind` and so
    // always forces a live refetch — the one thing that actually refreshes a
    // *round's* advancement status on this client, as opposed to one heat's
    // own lanes.
    const { raceId, racers } = await seedRace(page, 'Race Day Summary Reraise');
    await createSchedule(page, raceId, { name: 'Pack Final', numTopRacers: 3 });

    const rounds = await readRounds(page, raceId);
    const prelim = rounds.find((r) => r.advancementSource === null)!;
    const prelimHeats = (await readHeats(page, raceId))
        .filter((h) => h.roundId === prelim.id)
        .sort((a, b) => a.heatNumber - b.heatNumber);

    await recordRound(page, prelimHeats.slice(0, -1), racers);

    await page.goto(`/race/${raceId}/control/race`);
    await expect(page.getByText('Ready to start')).toBeVisible({ timeout: 30000 });
    await page.getByRole('button', { name: 'Start Timer' }).click();
    await page.getByRole('button', { name: 'Finish Heat' }).click();
    // The heat's own "Edit" button only appears once it holds a result — a
    // signal scoped to *this* heat, unlike counting rendered times, which
    // also matches every already-recorded heat listed under "Previous Heats".
    await expect(page.getByRole('button', { name: /^Edit(?! race)/ })).toBeVisible({
        timeout: 30000,
    });

    // The championship field just filled in live — the modal celebrating it
    // being decided.
    const summary = page.getByRole('dialog', { name: 'Round Complete!' });
    await expect(summary).toBeVisible({ timeout: 30000 });

    // Dismissed the ordinary way — an operator moving on to the next heat.
    // The modal's own "×" is `flow.dismissSummary`, not `handleNextHeat`, so
    // this does not touch `roundSummary` either way; it only hides the modal.
    await summary.getByRole('button', { name: '×' }).click();
    await expect(summary).toBeHidden();

    // Clear this heat's result through Edit — blanking every time field
    // sends exactly what `cleared()` sends for a Re-Run, so the backend
    // treats it identically, but this reaches it through the one path
    // (`handleUpdateResult`) that has no explicit clear site. The
    // preliminary round is no longer fully raced, so the championship
    // round's field reverts to placeholders.
    await page.getByRole('button', { name: /^Edit(?! race)/ }).click();
    const editor = page.getByRole('dialog', { name: /Edit Results/ });
    await expect(editor).toBeVisible();
    for (const input of await editor.locator('input[type="number"]').all()) {
        await input.fill('');
    }
    await editor.getByRole('button', { name: 'Save Results' }).click();
    await expect(editor).toBeHidden();

    // Run the same heat again — an ordinary "this one still needs a time"
    // action. The championship round becomes decided a second time.
    await expect(page.getByRole('button', { name: 'Start Timer' })).toBeVisible({
        timeout: 30000,
    });
    await page.getByRole('button', { name: 'Start Timer' }).click();
    await page.getByRole('button', { name: 'Finish Heat' }).click();

    // A round decided a second time deserves a summary a second time.
    await expect(summary).toBeVisible({ timeout: 30000 });
});

