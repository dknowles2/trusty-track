test('the wizard generates a schedule that fills every lane', async ({ page }) => {
    // #26: greedy lane filling finds a maximal matching, not a maximum one, and
    // used to strand a lane in roughly one in four four-lane schedules — which
    // under POINTS scoring made the short-changed racer's score *better*. The
    // property is held by `test_domain_scheduling.py`; this is the same claim
    // made about a schedule the operator actually generated by clicking.
    const { raceId, laneCount, racers } = await seedRace(page, 'Race Day Schedule');

    await page.goto(`/race/${raceId}/control`);
    await page.getByRole('button', { name: /Start Round Creation Wizard/i }).click();
    await expect(page.getByRole('heading', { name: 'Race Schedule Wizard' })).toBeVisible();
    await page.getByRole('button', { name: 'Next' }).click();
    await page.getByRole('button', { name: 'Next' }).click();
    await page.getByRole('button', { name: 'Generate schedule' }).click();

    await expect(page.getByText('Heat 1', { exact: true }).first()).toBeVisible({
        timeout: 30000,
    });

    // The wizard's own defaults add a championship round, whose lanes are
    // undecided slots rather than racers. This claim is about the preliminary
    // round, where the field is the roster.
    const prelim = (await readRounds(page, raceId)).find((r) => r.advancementSource === null)!;
    const heats = (await readHeats(page, raceId)).filter((h) => h.roundId === prelim.id);

    // Lane 1 is seeded with every racer, which fixes the heat count.
    expect(heats).toHaveLength(racers.length);
    for (const heat of heats) {
        expect(heat.lanes.filter((l) => l.racerId !== null)).toHaveLength(laneCount);
    }

    // Every racer therefore runs once per lane, and nobody runs a heat fewer.
    const appearances = new Map(racers.map((r) => [r.id, 0]));
    for (const heat of heats) {
        for (const lane of heat.lanes) {
            if (lane.racerId !== null) {
                appearances.set(lane.racerId, appearances.get(lane.racerId)! + 1);
            }
        }
    }
    expect([...appearances.values()]).toEqual(racers.map(() => laneCount));
});

test('a heat run on the timer records times that survive a reload', async ({ page }) => {
    // The whole timer path: arming over a subscription, the fake device driving
    // `TimerManager` through the same code a serial one does, the result
    // reaching the database, and the screen showing the stored record rather
    // than the pending times it was showing a moment earlier (#7).
    const { raceId, laneCount } = await seedRace(page, 'Race Day Timer');
    await createSchedule(page, raceId);

    await page.goto(`/race/${raceId}/control/race`);
    await expect(page.getByText('Ready to start')).toBeVisible({ timeout: 30000 });

    // No lane has a time before the heat is run — otherwise the assertion below
    // would pass against a heat that was already recorded.
    const times = page.getByText(/^\d+\.\d{3}s$/);
    await expect(times).toHaveCount(0);

    await page.getByRole('button', { name: 'Start Timer' }).click();
    await page.getByRole('button', { name: 'Finish Heat' }).click();

    await expect(times).toHaveCount(laneCount, { timeout: 30000 });

    // A time on screen is not yet a stored result: until `record_heat_result`
    // runs it is the manager's pending state, and an abort still loses it. The
    // schedule is where a fresh page load shows the record — the execution view
    // moves on to the first heat still to be run, which is the next one.
    await page.goto(`/race/${raceId}/control`);
    await expect(times).toHaveCount(laneCount, { timeout: 30000 });

    const [heat] = (await readHeats(page, raceId)).sort((a, b) => a.heatNumber - b.heatNumber);
    const run = heat.lanes.filter((l) => l.racerId !== null);
    expect(run.map((l) => l.time).every((t) => t !== null)).toBe(true);
    expect([...run].map((l) => l.place).sort((a, b) => a! - b!)).toEqual(
        Array.from({ length: laneCount }, (_, i) => i + 1),
    );
});

test('standings arrive over the subscription without a reload', async ({ page }) => {
    // The leaderboard is subscription-fed, so this is the one path where a
    // typed payload landing in the normalized cache is the whole feature (#12).
    // A query-backed version of this test would pass with the subscription
    // broken.
    const { raceId, racers } = await seedRace(page, 'Race Day Standings');
    await createSchedule(page, raceId);

    await page.goto(`/race/${raceId}/standings`);
    await expect(page.getByText('No results yet')).toBeVisible({ timeout: 30000 });

    const heats = await readHeats(page, raceId);
    await recordRound(page, heats, racers);

    // No reload: if the row appears, the subscription delivered it.
    const rows = page.getByRole('row');
    await expect(rows.filter({ hasText: 'Ada Ant' })).toBeVisible({ timeout: 30000 });

    // Car number decides the times `recordRound` writes, so the standings are
    // the roster in car-number order.
    const names = await page.getByRole('row').allInnerTexts();
    const ranked = names
        .slice(1)
        .map((row) => row.split('\t').find((cell) => /\w+ \w+/.test(cell)));
    expect(ranked.slice(0, 3)).toEqual(['Ada Ant', 'Ben Bear', 'Cy Cat']);

    // Everyone ran every heat of the round, so nobody is short.
    for (const row of await rows.all()) {
        const text = await row.innerText();
        if (text.includes('Rank')) continue;
        expect(text).not.toContain('\t-\t');
    }
});

test('finishing the prelims fills the championship round with the top finishers', async ({
    page,
}) => {
    // `record_heat_result` re-runs advancement on every result, so a final's
    // field is decided by the cascade rather than by an operator action. Until
    // it fires the round holds placeholders and `phase` reports NOT_READY,
    // which leaves the operator screen with no controls at all.
    const { raceId, racers } = await seedRace(page, 'Race Day Championship');
    await createSchedule(page, raceId, { name: 'Pack Final', numTopRacers: 3 });

    const rounds = await readRounds(page, raceId);
    const prelim = rounds.find((r) => r.advancementSource === null)!;
    const final = rounds.find((r) => r.advancementSource !== null)!;

    // Before any result, the final's lanes are undecided slots.
    await page.goto(`/race/${raceId}/control`);
    await expect(page.getByText('Placeholder 1', { exact: true }).first()).toBeVisible({
        timeout: 30000,
    });

    const heats = await readHeats(page, raceId);
    await recordRound(
        page,
        heats.filter((h) => h.roundId === prelim.id),
        racers,
    );

    await page.reload();
    await dismissRoundSummary(page);

    for (const name of ['Ada Ant', 'Ben Bear', 'Cy Cat']) {
        await expect(page.getByText(`${name} (#`, { exact: false }).first()).toBeVisible({
            timeout: 30000,
        });
    }
    await expect(page.getByText('Placeholder 1', { exact: true })).toHaveCount(0);

    const finalHeats = (await readHeats(page, raceId)).filter((h) => h.roundId === final.id);
    const fielded = new Set(
        finalHeats.flatMap((h) => h.lanes.map((l) => l.racerId).filter((id) => id !== null)),
    );
    expect([...fielded].sort((a, b) => a! - b!)).toEqual(
        racers
            .filter((r) => r.carNumber <= 3)
            .map((r) => r.id)
            .sort((a, b) => a - b),
    );
});

